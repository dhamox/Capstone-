"""
Clinical Manager Audit Trail Module
===================================
Project: Shift Workload-Balancing Simulator for Hospital Patient Transfers
Author: Hospital Operations Research & AI Engineering Team
Version: 3.0.0 (Review 3 Final Release)

Description:
    Provides an immutable, timestamped audit log capturing human clinical
    oversight decisions (Approval, Rejection, Override) made on algorithmically
    generated nurse reassignment recommendations.

Regulatory & Clinical Governance:
    - Enforces FDA/HIPAA SaMD (Software as a Medical Device) principle that
      automated decision-support tools must provide traceability of human intervention.
    - Captures operational rationale, user identity, source and destination units.
"""

import os
import sys
import pandas as pd
from datetime import datetime

# Ensure project root in sys.path
sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..")))


def record_manager_decision(
    recommendation_id: str,
    nurse_id: str,
    source_unit: str,
    dest_unit: str,
    user_role: str,
    decision: str,
    reason: str = "",
    audit_file: str = "data/audit_log.csv"
) -> pd.DataFrame:
    """
    Appends a clinical decision entry to the permanent audit trail log file.

    Parameters:
    -----------
    recommendation_id : str
        Unique recommendation ID generated by the simulation engine (e.g. 'REC-001').
    nurse_id : str
        ID of the nurse evaluated for reassignment.
    source_unit : str
        Unit releasing staff.
    dest_unit : str
        Unit receiving staff.
    user_role : str
        Role of authorizing individual (e.g. 'Shift Manager', 'Clinical Lead', 'Director').
    decision : str
        Outcome: 'Approved', 'Rejected', or 'Overridden'.
    reason : str, optional
        Clinical or operational rationale entered by the human manager.
    audit_file : str, default='data/audit_log.csv'
        Destination CSV file path for persistence.

    Returns:
    --------
    pd.DataFrame
        Updated audit log DataFrame.

    Error Boundaries:
    -----------------
    - Creates parent directory if missing.
    - Handles file locking / corrupt CSV scenarios gracefully.
    """
    parent_dir = os.path.dirname(audit_file)
    if parent_dir:
        os.makedirs(parent_dir, exist_ok=True)
    
    log_entry = {
        "Timestamp": datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
        "Recommendation_ID": str(recommendation_id),
        "Nurse_ID": str(nurse_id),
        "Source_Unit": str(source_unit),
        "Dest_Unit": str(dest_unit),
        "User_Role": str(user_role),
        "Decision": str(decision),
        "Reason": str(reason)
    }

    new_row_df = pd.DataFrame([log_entry])

    if os.path.exists(audit_file) and os.path.getsize(audit_file) > 0:
        try:
            df_log = pd.read_csv(audit_file)
            df_log = pd.concat([df_log, new_row_df], ignore_index=True)
        except Exception:
            df_log = new_row_df
    else:
        df_log = new_row_df

    df_log.to_csv(audit_file, index=False)
    return df_log


def load_audit_log(audit_file: str = "data/audit_log.csv") -> pd.DataFrame:
    """
    Loads historical clinical audit logs.

    Parameters:
    -----------
    audit_file : str, default='data/audit_log.csv'
        Path to the audit log CSV file.

    Returns:
    --------
    pd.DataFrame
        Table of historical decisions or empty DataFrame with schema if absent.
    """
    expected_cols = [
        "Timestamp", "Recommendation_ID", "Nurse_ID", "Source_Unit", 
        "Dest_Unit", "User_Role", "Decision", "Reason"
    ]
    if os.path.exists(audit_file) and os.path.getsize(audit_file) > 0:
        try:
            return pd.read_csv(audit_file)
        except Exception:
            return pd.DataFrame(columns=expected_cols)
    return pd.DataFrame(columns=expected_cols)


